/** Responsive candidates generated by scripts/optimize-images.mjs. */
export const srcSet = (image: string) => {
  const base = image.replace(/\.webp$/, '');
  return `${base}-640.webp 640w, ${base}-1024.webp 1024w, ${image} 1600w`;
};

